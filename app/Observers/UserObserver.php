        } catch (\Exception $e) {
            Log::error("Failed to generate Student ID Card for user {$user->id}: " . $e->getMessage());
        }
    }

    /**
     * Generate Library Card
     */
    private function generateLibraryCard(User $user): void
    {
        try {
            $student = \Modules\Academic\Models\Student::where('user_id', $user->id)->first();
            
            if ($student) {
                Log::info("Auto-generate Library Card for: {$user->name}");
                
                // You can also trigger an Artisan command here
                // \Artisan::call('documents:generate-library-card', ['student_id' => $student->id]);
            }
        } catch (\Exception $e) {
            Log::error("Failed to generate Library Card for user {$user->id}: " . $e->getMessage());
        }
    }

    /**
     * Generate Staff ID Card
     */
    private function generateStaffIdCard(User $user): void
    {
        try {
            Log::info("Auto-generate Staff ID Card for: {$user->name}");
            
            // You can also trigger an Artisan command here
            // \Artisan::call('documents:generate-staff-id', ['user_id' => $user->id]);
